// Builds netlify/lib/prompts.mjs from the on-stage agents in .claude/agents/
// plus the skills each one lists and its knowledge folder, so the live app
// runs the exact same agents the team uses in Claude Code.
// Runs on every Netlify build (see netlify.toml). No npm packages needed.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";

const ONSTAGE = ["prosecution-rater", "defense-rater", "judge", "spin-doctor", "then-vs-now-analyst"];

function split(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
  if (!m) throw new Error("missing frontmatter");
  const fm = {};
  for (const line of m[1].split("\n")) {
    const i = line.indexOf(":");
    if (i > 0) fm[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  return { fm, body: m[2].trim() };
}

const out = {};
for (const name of ONSTAGE) {
  const { fm, body } = split(readFileSync(`.claude/agents/${name}.md`, "utf8"));
  const skills = (fm.skills || "").replace(/[\[\]]/g, "").split(",").map((s) => s.trim()).filter(Boolean);
  const skillText = skills
    .map((s) => `### Skill: ${s}\n${split(readFileSync(`.claude/skills/${s}/SKILL.md`, "utf8")).body}`)
    .join("\n\n");
  const kPath = `knowledge/${name}/README.md`;
  const knowledge = existsSync(kPath) ? readFileSync(kPath, "utf8") : "";
  const system = [
    body.replace(/\*\*Before answering, always read[\s\S]*?when asked\.\n/, ""),
    "## Your knowledge folder\n" + knowledge,
    "## Your skills\n" + skillText,
    "## Output\nRespond with ONLY one JSON object in the shape described by the structured-json-output skill. No prose, no markdown fences. Keep it concise.",
  ].join("\n\n");
  out[name] = { model: fm.model, system };
}

mkdirSync("netlify/lib", { recursive: true });
writeFileSync(
  "netlify/lib/prompts.mjs",
  "// GENERATED by scripts/build-prompts.mjs from .claude/agents. Do not edit by hand.\n" +
    "export const PROMPTS = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log("Built prompts for:", Object.keys(out).join(", "));
